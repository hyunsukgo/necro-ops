/**
 * GET /api/incidents/[id]/report.md
 *
 * Export the autopsy report as a Markdown file download.
 *
 * Requirements: 6.1, 6.2
 *   6.1 — Download includes the timeline table and citations.
 *   6.2 — Exported Markdown MUST NOT include raw payloads or secret values.
 *
 * The raw payload is stored in the events table but is never included here.
 * Citations are rendered as `[event-id]` anchors.
 */

import { NextRequest, NextResponse } from "next/server";
import { ensureDb } from "@/lib/db";
import { getReportByIncident, getIncidentById } from "@necro-ops/db";
import type { Report } from "@necro-ops/core";

// ── Markdown builder ──────────────────────────────────────────────────────────

function citationsToMd(citations: string[]): string {
  return citations.map((c) => `\`${c}\``).join(", ");
}

function buildMarkdown(incident: { title: string; startAt: string; endAt: string }, report: Report): string {
  const lines: string[] = [];

  lines.push(`# Autopsy Report: ${incident.title}`);
  lines.push("");
  lines.push(
    `> **Period:** ${incident.startAt} → ${incident.endAt}  `,
  );
  lines.push(
    `> **Generated by:** ${report.generatedBy}  `,
  );
  lines.push(
    `> **Status:** ${report.isDraft ? "Draft" : "Final"}`,
  );
  lines.push("");

  // Summary
  lines.push("## Summary");
  lines.push("");
  lines.push(report.summary);
  lines.push("");

  // Cause of Death
  lines.push("## Cause of Death");
  lines.push("");
  for (const item of report.causeOfDeath) {
    lines.push(`- ${item.text} *(${citationsToMd(item.citations)})*`);
  }
  lines.push("");

  // Contributing Factors
  lines.push("## Contributing Factors");
  lines.push("");
  for (const item of report.contributingFactors) {
    lines.push(`- ${item.text} *(${citationsToMd(item.citations)})*`);
  }
  lines.push("");

  // Impact
  lines.push("## Impact");
  lines.push("");
  lines.push(report.impact);
  lines.push("");

  // Detection & Response
  lines.push("## Detection & Response");
  lines.push("");
  lines.push(report.detectionAndResponse);
  lines.push("");

  // Timeline table — already built as Markdown by templateReport / generate
  lines.push("## Timeline");
  lines.push("");
  lines.push(report.timeline);
  lines.push("");

  // Action Items
  lines.push("## Action Items");
  lines.push("");
  lines.push("| Priority | Type | Action |");
  lines.push("|---|---|---|");
  for (const item of report.actionItems) {
    lines.push(`| ${item.priority} | ${item.type} | ${item.title} |`);
  }
  lines.push("");

  return lines.join("\n");
}

// ── Route handler ─────────────────────────────────────────────────────────────

export async function GET(
  _req: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  const { id } = await params;
  await ensureDb();

  const [incident, row] = await Promise.all([
    getIncidentById(id),
    getReportByIncident(id),
  ]);

  if (!incident) {
    return NextResponse.json({ error: "Incident not found" }, { status: 404 });
  }

  if (!row) {
    return NextResponse.json({ error: "Report not found" }, { status: 404 });
  }

  const report = JSON.parse(row.bodyJson) as Report;
  const markdown = buildMarkdown(incident, report);

  // Suggest a safe filename
  const slug = incident.title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 60);

  return new Response(markdown, {
    headers: {
      "Content-Type": "text/markdown; charset=utf-8",
      "Content-Disposition": `attachment; filename="autopsy-${slug}.md"`,
    },
  });
}
